use DCarbone\PHPFHIR\Render\Templates;
use DCarbone\PHPFHIR\Utilities\FileUtils;
use RuntimeException;

/**
 * Writes the generated profile classes of one FHIR version, along with the version's profile map and autoloader.
 */
class ProfileWriter
{
    /**
     * Writes everything for a version in one go.  Memory-hungry for large package sets; prefer {@see self::writeClasses()}
     * one package at a time followed by {@see self::writeSupport()}.
     *
     * @param string $libraryPath Root output directory.
     * @param string $profilesNamespace Fully qualified namespace of the version's profiles, without leading slash.
     * @param string $copyright Pre-rendered copyright comment.
     * @param array<string, ProfileClasses> $packages Package name => classes.
     * @param array<string, string> $coreTypes Fully qualified names, without leading slash, of the core enums and interfaces referred to, by entity name.
     * @param null|string[] $writePackages Package names to write class files for.  If null, all of them.  The map and
     *                                     autoloader always cover every package.
     * @return string[] Paths of the files written.
     */
    public static function write(
        string     $libraryPath,
        string     $profilesNamespace,
        string     $copyright,
        array      $packages,
        array      $coreTypes,
        null|array $writePackages = null,
    ): array {
        $written = [];
        $index = self::newIndex();
        foreach ($packages as $packageName => $classes) {
            $write = null === $writePackages || in_array($packageName, $writePackages, true);
            array_push($written, ...self::writeClasses($libraryPath, $profilesNamespace, $copyright, $packageName, $classes, $index, $write));
        }
        array_push($written, ...self::writeSupport($libraryPath, $profilesNamespace, $copyright, $index, $coreTypes));
        return $written;
    }

    /**
     * @return array{urls: array<string, string>, namespaces: array<string, true>}
     */
    public static function newIndex(): array
    {
        return ['urls' => [], 'namespaces' => []];
    }

    /**
     * Records one package's classes in $index and, if $write is true, writes their files.  The package's own map and
     * autoloader are always written.
     *
     * @param array $index Index from {@see self::newIndex()}, updated in place.
     * @return string[] Paths of the files written.
     */
    public static function writeClasses(
        string         $libraryPath,
        string         $profilesNamespace,
        string         $copyright,
        string         $packageName,
        iterable       $classes,
        array          &$index,
        bool           $write = true,
    ): array {
        $written = [];
        $namespaces = [];
        foreach ($classes as $url => $class) {
            /** @var ProfileClass $class */
            $fqcn = $class->getFullyQualifiedClassName(false);
            if (isset($index['urls'][$url])) {
                throw new ProfileDefinitionException(sprintf(
                    'Profile "%s" is generated by more than one package (including "%s")',
                    $url,
                    $packageName,
                ));
            }
            $index['urls'][$url] = $packageName;
            $namespace = $class->getPackageNamespace();
            $index['namespaces'][$namespace] = true;
            $relative = substr($class->getNamespace(), strlen($namespace) + 1);
            $namespaces[$namespace]['fileMap'][$fqcn] = ('' === $relative ? '' : str_replace('\\', '/', $relative) . '/') . $class->getClassName() . '.php';
            $namespaces[$namespace]['classMap'][$url] = $fqcn;
            $namespaces[$namespace]['baseTypeMap'][$url] = $class->getProfile()->getType();

            if ($write) {
                $written[] = self::_put($libraryPath, $fqcn, Templates::renderProfileClass($copyright, $class));
            }
        }

        // the package's map is cheap, and the profiles map covers every package whether or not its classes are written.
        foreach ($namespaces as $namespace => $package) {
            $mapFQCN = $namespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_PACKAGE_MAP;
            $package['fileMap'][$mapFQCN] = PHPFHIR_PROFILES_CLASSNAME_PACKAGE_MAP . '.php';
            $written[] = self::_put($libraryPath, $mapFQCN, Templates::renderProfilePackageMap(
                $copyright,
                $namespace,
                PHPFHIR_PROFILES_CLASSNAME_PACKAGE_MAP,
                $package['classMap'],
                $package['baseTypeMap'],
                $profilesNamespace . '\\' . PHPFHIR_PROFILES_INTERFACE_PACKAGE_MAP,
            ));
            $written[] = self::_put($libraryPath, $namespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_PACKAGE_AUTOLOADER, Templates::renderProfilePackageAutoloader(
                $copyright,
                $namespace,
                PHPFHIR_PROFILES_CLASSNAME_PACKAGE_AUTOLOADER,
                $package['fileMap'],
                $profilesNamespace . '\\' . PHPFHIR_PROFILES_INTERFACE_PACKAGE_AUTOLOADER,
            ));
        }
        return $written;
    }

    /**
     * Writes the profiles map and autoloader.
     *
     * @param array $index Index populated by {@see self::writeClasses()}.
     * @param array<string, string> $coreTypes Fully qualified names, without leading slash, of the core enums and interfaces referred to, by entity name.
     * @return string[] Paths of the files written.
     */
    public static function writeSupport(string $libraryPath, string $profilesNamespace, string $copyright, array $index, array $coreTypes): array
    {
        $written = [];
        $packageMaps = [];
        $packages = [];
        foreach (array_keys($index['namespaces']) as $namespace) {
            $packageMaps[] = $namespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_PACKAGE_MAP;
            $packages[] = [
                'namespace' => $namespace,
                'autoloader' => $namespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_PACKAGE_AUTOLOADER,
                'path' => str_replace('\\', '/', substr($namespace, strlen($profilesNamespace) + 1)) . '/' . PHPFHIR_PROFILES_CLASSNAME_PACKAGE_AUTOLOADER . '.php',
            ];
        }
        $fileMap = [$profilesNamespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_MAP => PHPFHIR_PROFILES_CLASSNAME_MAP . '.php'];
        foreach ([PHPFHIR_PROFILES_INTERFACE_PACKAGE_MAP, PHPFHIR_PROFILES_INTERFACE_PACKAGE_AUTOLOADER] as $interface) {
            $fileMap[$profilesNamespace . '\\' . $interface] = $interface . '.php';
        }
        $written[] = self::_put($libraryPath, $profilesNamespace . '\\' . PHPFHIR_PROFILES_INTERFACE_PACKAGE_MAP, Templates::renderProfilePackageMapInterface(
            $copyright,
            $profilesNamespace,
            PHPFHIR_PROFILES_INTERFACE_PACKAGE_MAP,
        ));
        $written[] = self::_put($libraryPath, $profilesNamespace . '\\' . PHPFHIR_PROFILES_INTERFACE_PACKAGE_AUTOLOADER, Templates::renderProfilePackageAutoloaderInterface(
            $copyright,
            $profilesNamespace,
            PHPFHIR_PROFILES_INTERFACE_PACKAGE_AUTOLOADER,
        ));
        $written[] = self::_put($libraryPath, $profilesNamespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_MAP, Templates::renderProfileMap(
            $copyright,
            $profilesNamespace,
            PHPFHIR_PROFILES_CLASSNAME_MAP,
            $packageMaps,
            $coreTypes,
        ));
        $written[] = self::_put($libraryPath, $profilesNamespace . '\\' . PHPFHIR_PROFILES_CLASSNAME_AUTOLOADER, Templates::renderProfileAutoloader(
            $copyright,
            $profilesNamespace,
            PHPFHIR_PROFILES_CLASSNAME_AUTOLOADER,
            $fileMap,
            $packages,
        ));

        return $written;
    }

    private static function _put(string $libraryPath, string $fqcn, string $contents): string
    {
        $pos = strrpos($fqcn, '\\');
        $path = FileUtils::compileNamespaceFilepath($libraryPath, substr($fqcn, 0, $pos))
            . DIRECTORY_SEPARATOR . substr($fqcn, $pos + 1) . '.php';
        FileUtils::mkdirRecurse($path);
        if (false === file_put_contents($path, $contents)) {
            throw new RuntimeException(sprintf('Unable to write profile file %s', $path));
        }
        return $path;
    }
}
