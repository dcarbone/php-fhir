use DCarbone\PHPFHIR\Config\ProfilePackageConfig;
use DCarbone\PHPFHIR\Profiles\ProfileClasses;
use DCarbone\PHPFHIR\Profiles\ProfilePackage;
use DCarbone\PHPFHIR\Profiles\ProfilePackageReader;
use DCarbone\PHPFHIR\Profiles\ProfileSet;
use PHPUnit\Framework\TestCase;
use Spatie\TemporaryDirectory\TemporaryDirectory;

class ProfileClassesTest extends TestCase
{
    use PackageFixtures;

    private const _BASE = 'http://example.org/fhir/StructureDefinition/';

    private TemporaryDirectory $_tmpdir;

    protected function setUp(): void
    {
        $this->_tmpdir = new TemporaryDirectory(sys_get_temp_dir() . DIRECTORY_SEPARATOR . 'ProfileClassesTest');
        $this->_tmpdir->create();
    }

    protected function tearDown(): void
    {
        $this->_tmpdir->delete();
    }

    private function package(string $name, array $sds, array $config = [], array $deps = []): ProfilePackage
    {
        $files = ['package.json' => self::manifest($name)];
        foreach ($sds as $sd) {
            $files['StructureDefinition-' . $sd['id'] . '.json'] = $sd;
        }
        $path = rtrim($this->_tmpdir->path(''), '/') . '/' . $name;
        self::writePackageDir($path, $files);
        return ProfilePackageReader::read(
            ProfilePackageConfig::fromArray(array_merge(['name' => $name, 'source' => $path], $config)),
            null,
            $deps,
        );
    }

    private function build(ProfileSet $set, string $ns, array $depClasses = []): ProfileClasses
    {
        return ProfileClasses::build($set, 'Ns\\Profiles', $ns, TypeStubs::resolver('Ns'), null, $depClasses);
    }

    private function child(string $id, string $parentId): array
    {
        return self::structureDefinition($id, 'Patient', 'constraint', ['baseDefinition' => self::_BASE . $parentId]);
    }

    public function testDependentExtendsDependencyClass(): void
    {
        $dep = $this->package('dep.ig', [self::structureDefinition('dep-base')]);
        $mine = $this->package('mine.ig', [$this->child('mine', 'dep-base')], [], [$dep]);

        $depClasses = $this->build(new ProfileSet($dep), 'Dep');
        $this->assertCount(1, $depClasses);

        $mineClasses = $this->build(new ProfileSet($mine), 'Mine', iterator_to_array($depClasses));
        $this->assertSame('\\Ns\\Profiles\\Dep\\DepBase', $mineClasses->getByUrl(self::_BASE . 'mine')->getExtendsClassName());
        // only mine's own class is generated by the dependent.
        $this->assertCount(1, $mineClasses);
    }

    public function testMissingDependencyClassFallsBackToBaseType(): void
    {
        $dep = $this->package('dep.ig', [self::structureDefinition('dep-base')]);
        $mine = $this->package('mine.ig', [$this->child('mine', 'dep-base')], [], [$dep]);
        $classes = $this->build(new ProfileSet($mine), 'Mine');
        $this->assertSame('\\Ns\\Versions\\R4\\Types\\FHIRPatient', $classes->getByUrl(self::_BASE . 'mine')->getExtendsClassName());
    }

    public function testExtensionProfilesAreNotGenerated(): void
    {
        $set = new ProfileSet($this->package('a.ig', [
            self::structureDefinition('a-ext', 'Extension'),
            self::structureDefinition('a-patient'),
        ]));
        $classes = ProfileClasses::build($set, 'Ns\\Profiles', 'A', TypeStubs::resolver('Ns'));
        $this->assertCount(1, $classes);
        $this->assertNotNull($classes->getByUrl(self::_BASE . 'a-patient'));
    }

}
